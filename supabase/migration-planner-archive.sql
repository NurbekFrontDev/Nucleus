-- =====================================================================
-- Миграция: Архив дел (подвкладка «Архив» в «Мои дела»).
-- Запустить ОДИН раз в Supabase SQL Editor.
--
-- archived_at — дата, когда дело положили в архив. Семантика:
--   * со дня archived_at и во все последующие дни дело НЕ показывается
--     (исчезает из «Сегодня», «Календаря» и будущих дней);
--   * все дни ДО archived_at остаются в истории как есть (дело там
--     продолжает отображаться со своими отметками выполнения).
-- Для старых архивированных дел (выполненные разовые) колонка остаётся
-- NULL — их поведение не меняется (видны только в днях с отметками).
-- =====================================================================

alter table planner_items add column if not exists archived_at date;
