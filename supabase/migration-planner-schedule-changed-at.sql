-- Planner: момент последнего изменения РАСПИСАНИЯ дела.
--
-- Зачем: до этого прошлые дни собирались по ТЕКУЩЕМУ правилу повтора.
-- Из-за этого, если поменять дни недели (напр. Вт -> Пн), дело ЗАДНИМ
-- ЧИСЛОМ появлялось в прошлых понедельниках, где его тогда не было.
--
-- Теперь: если дата раньше schedule_changed_at, день считается историей и
-- собирается ТОЛЬКО из фактов: снимка planner_day_overrides или отметки
-- planner_logs. Новое расписание действует только с сегодняшнего дня и вперёд.

alter table public.planner_items
  add column if not exists schedule_changed_at date;
